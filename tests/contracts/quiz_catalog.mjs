import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const id='11111111-1111-4111-8111-111111111111';
let plans=[{id,name:'Published QA',service:'internet',speed_mbps:321}];
let selection;
const context=vm.createContext({document:{getElementById(){return null;}},getPublishedPlans:()=>plans,openBottomSheet:(...args)=>selection=args});
vm.runInContext(fs.readFileSync('src/pagefpt/static/js/client/quiz.js','utf8'),context);
context.calculateRecommendation();
context.applyQuizRecommendation();
assert.equal(selection[2],id,'Quiz must carry a published plan UUID');
assert.equal(selection[0],'Published QA');
assert.equal(selection[1],'','Quiz must not invent a fixed price');
plans=[];
context.calculateRecommendation();
context.applyQuizRecommendation();
assert.equal(selection[2],null,'Empty catalog must use general consultation');
assert.match(selection[0],/Tư vấn/);
console.log('Quiz catalog: published UUID and empty-catalog consultation passed.');
