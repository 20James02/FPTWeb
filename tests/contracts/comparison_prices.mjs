import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const id='11111111-1111-4111-8111-111111111111';
const label={dataset:{quotePlan:id},textContent:'old-price'};
const comparison={id,fee:'old-price'};
let fulfill;
const context=vm.createContext({AbortController,setTimeout,clearTimeout,window:{},document:{querySelectorAll:selector=>selector==='[data-quote-plan]'?[label]:[],getElementById:()=>null,addEventListener(){}},compareItems:[comparison],renderCompareCards(){},Intl,AbortSignal,fetch:()=>new Promise(resolve=>fulfill=resolve)});
vm.runInContext(fs.readFileSync('src/pagefpt/static/js/client/catalog.js','utf8'),context);
const pending=context.refreshCatalogPrices('22222222-2222-4222-8222-222222222222');
assert.equal(comparison.fee,'Cần tư vấn','Region change immediately invalidates comparison prices');
fulfill({ok:true,json:async()=>({status:'confirmed',monthly_vnd:200,initial_total_vnd:1200,billing_months:6})});
await pending;
assert.equal(comparison.fee,label.textContent);
assert.equal(comparison.fee,'200đ');
await context.refreshCatalogPrices();
assert.equal(comparison.fee,'Cần tư vấn','Cleared region cannot retain confirmed prices');
console.log('Comparison prices: region invalidation and quote refresh passed.');
// Navigating away must stop the remaining quote queue, including stale UI writes.
const lifecycle={}, queue=[], cards=Array.from({length:5},(_,i)=>({dataset:{quotePlan:'plan-'+i},textContent:''}));
const navigation=vm.createContext({AbortController,setTimeout,clearTimeout,window:{addEventListener:(name,handler)=>lifecycle[name]=handler},document:{querySelectorAll:s=>s==='[data-quote-plan]'?cards:[],getElementById:()=>null,addEventListener(){}},Intl,AbortSignal,fetch:(url,options)=>new Promise(resolve=>queue.push({resolve,signal:options.signal}))});
vm.runInContext(fs.readFileSync('src/pagefpt/static/js/client/catalog.js','utf8'),navigation);
const oldQueue=navigation.refreshCatalogPrices('22222222-2222-4222-8222-222222222222');
assert.equal(queue.length,3);
lifecycle.pagehide();
assert.ok(queue.every(item=>item.signal.aborted),'In-flight requests are canceled on pagehide');
for(const {resolve} of queue)resolve({ok:true,json:async()=>({status:'confirmed',monthly_vnd:100,billing_months:6,initial_total_vnd:600})});
await oldQueue;
assert.equal(queue.length,3,'No new request starts in a leaving document');
assert.ok(cards.every(c=>c.textContent==='Cần tư vấn'),'Stale responses cannot update departing page');
console.log('Catalog stops quote queue on pagehide PASS');
