"""Structural interfaces for provider adapters; domain code need not know HTTP clients."""

from typing import Any, Protocol


class Database(Protocol):
    async def rpc(self, name: str, payload: dict, actor_token: str | None = None) -> Any: ...
    async def close(self) -> None: ...


class ObjectStorage(Protocol):
    async def write(self, key: str, content: bytes, content_type: str) -> None: ...
    async def delete(self, key: str) -> None: ...
    async def delete_prefix(self, prefix: str) -> bool: ...
